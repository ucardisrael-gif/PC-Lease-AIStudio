from pathlib import Path
from docx import Document

root = Path('contracts_for_legal_review')
for kind in ('rental', 'leasing'):
    document = Document(root / f'computer_{kind}_he_battery_70.docx')
    seen=set()
    for paragraph in document.paragraphs:
        text=paragraph.text
        new=None
        if kind=='rental' and text.startswith('ההצעה תקבע תעריפים רלוונטיים'):
            new=('תעריפי העסקה לכל התקופה יימסרו ויוסכמו מראש. עבור שכירות מעבר ל־365 ימים תימסר הצעת מחיר נפרדת להמשך התקופה, לפני ההתקשרות לתקופה זו או לפני הארכת השכירות אליה; המחיר אינו משתנה באופן חד־צדדי בדיעבד. '
                 'החברה רשאית להציע גם הסכם ליסינג חדש כאפשרות נפרדת; הבחירה בידי הלקוח ואין מעבר אוטומטי לליסינג. עד להסכמה לא נקבע תעריף לתקופה שמעבר ל־365 ימים. תוקפם של תנאים קיימים וזכויות לפי דין נשמרים.')
            seen.add('365')
        if text.startswith('נזק מקרי, נזקי נוזלים'):
            base=('נזק מקרי, נזקי נוזלים, אביזרים שאבדו, שחזור קבצים אישיים, רישיונות בתשלום, התקנת תוכנות צד שלישי וביקור טכנאי אינם כלולים אוטומטית; האחריות והתשלום ייבחנו לפי הנסיבות, ההסכם והדין. עבודה שאינה כלולה תתומחר מראש ותבוצע לאחר הסכמת הלקוח, אלא אם הדין קובע אחרת. ')
            new=base+('במסגרת ליסינג החברה תארגן איסוף המחשב לתיקון והחזרתו לאחר התיקון על חשבונה. הוצאות אפשריות הקשורות לעבודה שאינה כלולה יימסרו מראש ללקוח ויוסכמו עמו, בכפוף לדין.' if kind=='leasing' else 'בשכירות אופן ההובלה לתיקון וממנו, הגורם האחראי והעלות יוסכמו מראש בעת ההזמנה ויפורטו בנספח. זכויות הלקוח לפי דין נשמרות.')
            seen.add('repair')
        if kind=='leasing' and text.startswith('התחזוקה והתיקון בידי החברה'):
            new=('התחזוקה והתיקון בידי החברה כלולים בתשלום החודשי לתקופת ההסכם, בהתאם לכיסוי ולחריגים שיפורטו בנספח ובהצעה. במהלך התיקון החברה תספק מחשב חלופי מאותה קטגוריה, נייד או נייח, ובעל מאפיינים המספיקים לעבודה הרגילה של הלקוח. '
                 'החברה תארגן את מסירת המחשב החלופי ואת איסופו על חשבונה. דרישות מיוחדות, לרבות מערכת הפעלה או זיכרון, יפורטו ויוסכמו מראש בהזמנה. מועד המסירה יתואם בנפרד; לא הוסכם בטיוטה זו מועד מרבי. '
                 'הציוד החלופי יתועד במסירה לפי דגם, מספר סידורי, מצב ואביזרים; אופן החזרה: __________.')
            seen.add('replacement')
        if kind=='leasing' and text.startswith('בסוף 36 החודשים הלקוח רשאי'):
            new=('בסוף 36 החודשים הלקוח רשאי לבחור בין החזרת הציוד, רכישתו בתשלום נוסף במחיר שנקבע מראש לכל מכשיר בנספח וכולל מע״מ בכפוף לדין, או החזרתו והתקשרות בהסכם חדש לציוד אחר. '
                 'מחיר הרכישה הקבוע ופרטי מימוש אפשרות הרכישה יסוכמו ויירשמו לפני חתימת כל הסכם; אין בטיוטה זו סכום מוסכם ואין העברת בעלות אוטומטית. '
                 'מחיר ותנאי הרכישה לכל מכשיר: __________. בהיעדר סכום ממולא בטיוטה לא נקבע מחיר; יש להשלים את התנאים לפני השימוש ולהעבירם לבדיקת עורך דין ורואה חשבון.')
            seen.add('buyout')
        if kind=='leasing' and text.startswith('מחיר ותנאי רכישה בסיום, אם יוסכמו'):
            new='מחיר רכישה קבוע לכל מכשיר, כולל מע״מ, ותנאי מימוש שייקבעו לפני החתימה __________. תנאי הכנה מיוחדת __________.'
            seen.add('appendix')
        if new is not None:
            paragraph.runs[0].text=new
            for run in paragraph.runs[1:]: run.text=''
    expected={'365','repair'} if kind=='rental' else {'repair','replacement','buyout','appendix'}
    if seen!=expected: raise RuntimeError(f'{kind}: {seen} != {expected}')
    document.save(root / f'computer_{kind}_he_updated_terms.docx')
